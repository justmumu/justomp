import { join, relative, resolve } from "node:path";
import type { TypecheckPolicy } from "../../config/typecheck/model";
import { readProjectionFile } from "../../lint/files";
import { contentHash } from "../freshness";
import {
  javascriptCheckContexts,
  readJavascriptConfigGraph,
} from "../javascript/config-graph";
import { TypecheckError } from "../model";
import type { ProjectionPlan } from "../projection";
import { TypecheckStateStore } from "../state";
import type { TypecheckTarget } from "../targets";
export const STRICT_OPTIONS = [
  "noImplicitAny",
  "noImplicitThis",
  "strictNullChecks",
  "strictFunctionTypes",
  "strictBindCallApply",
  "strictPropertyInitialization",
  "alwaysStrict",
  "useUnknownInCatchVariables",
  "strictBuiltinIteratorReturn",
] as const;
export async function planJavascriptProjection(
  target: TypecheckTarget,
  policy: TypecheckPolicy,
  signal: AbortSignal,
  entryConfig?: string,
): Promise<ProjectionPlan> {
  const graph = await readJavascriptConfigGraph(target, signal, entryConfig);
  const contexts = javascriptCheckContexts(target, graph);
  const store = await TypecheckStateStore.load(target.root);
  const declarations = Object.assign(
    {},
    ...Object.values(store.state.generated ?? {}).map(
      (receipt) => receipt.declarations ?? {},
    ),
  ) as Record<string, string>;
  const files: ProjectionPlan["files"] = [];
  const fingerprint = contentHash(JSON.stringify(graph.nodes));
  for (const [index, context] of contexts.entries()) {
    const path = join(target.scope.cwd, `tsconfig.justomp.${index}.json`);
    const before = await readProjectionFile(target.root, path);
    const marker = "// Generated by justomp; managed typecheck policy v1.\n";
    if (before.text !== null && !before.text.startsWith(marker))
      throw new TypecheckError(
        "projection-conflict",
        `Config filename is not owned by justomp: ${path}`,
      );
    const shared = policy.javascript.compilerOptions;
    const config = {
      ...(context.node ? { extends: context.node.path } : {}),
      compilerOptions: {
        ...(!context.node
          ? {
              target: "ESNext",
              module: "NodeNext",
              moduleResolution: "NodeNext",
              jsx: "preserve",
            }
          : {}),
        ...Object.fromEntries(
          STRICT_OPTIONS.map((key) => [key, shared.strict]),
        ),
        ...shared,
        // Production rootDir constrains emit, not the expanded source/test check.
        rootDir: target.root,
        noEmit: true,
        noCheck: false,
        emitDeclarationOnly: false,
        incremental: false,
        composite: false,
      },
      files: context.files.map(
        (file) => `./${relative(target.scope.cwd, file).replaceAll("\\", "/")}`,
      ),
      include: [],
      exclude: [],
      references:
        context.node?.references.map((path) => ({
          path: declarations[relative(target.root, path)]
            ? resolve(
                target.root,
                declarations[relative(target.root, path)] as string,
              )
            : path,
        })) ?? [],
    };
    const content = `${marker}// Native config graph: ${fingerprint}\n${JSON.stringify(config, null, 2)}\n`;
    files.push({ path, before, content, changed: before.text !== content });
  }
  return {
    target,
    files,
    configs: { check: files.map((file) => file.path) },
    current: files.every((file) => !file.changed),
  };
}
