import { relative, resolve } from "node:path";
import type { LintPolicy } from "../config/lint/model";
import { equivalentConfig, hasProjectionMarker } from "../format/readiness";
import type { ToolVersions } from "./adapters/types";
import {
  type FileSnapshot,
  publishProjectionFile,
  readProjectionFile,
  removeProjectionFile,
} from "./files";
import { BIOME_PACKAGE } from "./javascript/tools";
import { LintError, type PreparationChange } from "./model";
import { projectGo } from "./projections/go";
import {
  JS_MARKER,
  PRETTIER_SCHEMA,
  projectJavascript,
} from "./projections/javascript";
import { projectPython } from "./projections/python";
import { collectLintScope } from "./scope";
import type { LintTarget } from "./targets";

export const GO_MARKER = "# Generated by justomp; managed lint policy v1.\n";
export interface ProjectionFile {
  path: string;
  before: FileSnapshot;
  content: string;
  changed: boolean;
}
export interface ProjectionPlan {
  target: LintTarget;
  files: ProjectionFile[];
  /** Explicit native paths; callers must pass these instead of auto-discovery. */
  configs: { lint: string; format: string };
  current: boolean;
  retired?: { path: string; before: FileSnapshot }[];
}
/** Read-only freshness planning. Apply only after resolving again under the lease. */
export async function planProjection(
  target: LintTarget,
  policy: LintPolicy,
  versions: ToolVersions = {},
): Promise<ProjectionPlan> {
  const files: ProjectionFile[] = [];
  const retired: { path: string; before: FileSnapshot }[] = [];
  const add = async (
    name: string,
    render: (text: string | null) => string,
    owned?: (text: string) => boolean,
  ) => {
    const path = resolve(target.scope.cwd, name);
    const before = await readProjectionFile(target.root, path);
    if (before.text !== null && owned && !owned(before.text))
      throw new LintError(
        "projection-conflict",
        `Config filename is not owned by justomp: ${path}`,
      );
    const content = render(before.text);
    const parser = name.endsWith(".toml")
      ? "toml"
      : name.endsWith(".mjs")
        ? "babel"
        : name.endsWith(".yml")
          ? "yaml"
          : name.endsWith(".jsonc")
            ? "jsonc"
            : "json";
    const changed = !(await equivalentConfig(before.text, content, parser));
    files.push({
      path,
      before,
      content: changed ? content : (before.text ?? content),
      changed,
    });
    return path;
  };
  let lint: string, format: string;
  if (target.project.ecosystem === "python") {
    lint = format = await add("pyproject.toml", (text) => {
      if (text === null)
        throw new LintError(
          "project-not-found",
          "Python manifest disappeared before projection",
        );
      return projectPython(text, policy.python);
    });
  } else if (target.project.ecosystem === "javascript") {
    const scope = await collectLintScope(target);
    lint = await add(
      "biome.justomp.jsonc",
      () =>
        projectJavascript(
          target,
          policy.javascript,
          scope,
          versions[BIOME_PACKAGE] ?? "",
        ),
      (text) => hasProjectionMarker(text, JS_MARKER),
    );
    const legacyPath = resolve(target.scope.cwd, "eslint.justomp.config.mjs");
    const legacy = await readProjectionFile(target.root, legacyPath);
    if (legacy.text !== null && hasProjectionMarker(legacy.text, JS_MARKER))
      retired.push({ path: legacyPath, before: legacy });
    format = await add(
      "prettier.justomp.json",
      () =>
        `${JSON.stringify({ ...policy.javascript.prettier, $schema: PRETTIER_SCHEMA }, null, 2)}\n`,
      (text) => {
        try {
          return JSON.parse(text).$schema === PRETTIER_SCHEMA;
        } catch {
          return false;
        }
      },
    );
  } else {
    lint = format = await add(
      "golangci.justomp.yml",
      () => GO_MARKER + projectGo(policy.go),
      (text) => hasProjectionMarker(text, GO_MARKER),
    );
  }
  return {
    target,
    files,
    configs: { lint, format },
    current: files.every((file) => !file.changed) && retired.length === 0,
    retired,
  };
}
/** Changes are appended as published, including when a later file fails. */
export async function applyProjection(
  plan: ProjectionPlan,
  changes: PreparationChange[] = [],
): Promise<PreparationChange[]> {
  for (const file of plan.files) {
    if (!file.changed) continue;
    await publishProjectionFile(
      plan.target.root,
      file.path,
      file.before,
      file.content,
    );
    changes.push({
      project_id: plan.target.project.project_id,
      path: relative(plan.target.root, file.path).replaceAll("\\", "/"),
      kind: file.before.text === null ? "created" : "updated",
    });
  }
  for (const file of plan.retired ?? []) {
    await removeProjectionFile(plan.target.root, file.path, file.before);
    changes.push({
      project_id: plan.target.project.project_id,
      path: relative(plan.target.root, file.path).replaceAll("\\", "/"),
      kind: "removed",
    });
  }
  return changes;
}
