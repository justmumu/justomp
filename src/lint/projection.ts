export const GO_MARKER = "# Generated by justomp; managed lint policy v1.\n";
export interface ProjectionFile {
  path: string;
  before: FileSnapshot;
  content: string;
  changed: boolean;
}
export interface ProjectionPlan {
  target: LintTarget;
  files: ProjectionFile[];
  /** Explicit native paths; callers must pass these instead of auto-discovery. */
  configs: { lint: string; format: string };
  current: boolean;
  native_configs?: NativeConfigOwnership;
  inputs?: { path: string; before: FileSnapshot }[];
  retired?: { path: string; before: FileSnapshot }[];
}
function projectionParser(name: string) {
  if (name.endsWith(".toml")) {
    return "toml";
  }
  if (/\.[cm]?ts$/.test(name)) {
    return "typescript";
  }
  if (/\.[cm]?js$/.test(name)) {
    return "babel";
  }
  if (/\.ya?ml$/.test(name) || name.endsWith("/.prettierrc")) {
    return "yaml";
  }
  if (name.endsWith(".jsonc")) {
    return "jsonc";
  }
  if (name.endsWith(".json5")) {
    return "json5";
  }
  return "json";
}
class ProjectionBuilder {
  readonly files: ProjectionFile[] = [];
  readonly retired: { path: string; before: FileSnapshot }[] = [];
  readonly inputs: { path: string; before: FileSnapshot }[] = [];
  readonly metadata: NativeConfigOwnership = { version: 1, configs: [] };
  constructor(
    readonly target: LintTarget,
    readonly policy: LintPolicy,
    readonly receipt: NativeConfigOwnership | undefined,
  ) {}
  local(path: string): string {
    return relative(this.target.root, path).replaceAll("\\", "/");
  }
  previous(path: string, role: string): string[][] {
    return (
      this.receipt?.configs.find((config) => config.path === this.local(path) && config.role === role)?.fields ?? []
    );
  }
  async add(
    selected: NativeSelection,
    role: string,
    desired: Record<string, unknown>,
    extraPrevious: string[][] = [],
  ): Promise<string> {
    const edited = editNativeConfig(
      selected.before.text,
      selected.path,
      desired,
      [...this.previous(selected.path, role), ...extraPrevious],
      selected.prefix,
    );
    await this.record(selected, role, edited);
    return selected.path;
  }
  async record(
    selected: NativeSelection,
    role: string,
    edited: { content: string; fields: string[][] },
  ): Promise<void> {
    const changed = !(await equivalentConfig(selected.before.text, edited.content, projectionParser(selected.path)));
    this.files.push({
      path: selected.path,
      before: selected.before,
      content: changed ? edited.content : (selected.before.text ?? edited.content),
      changed,
    });
    this.metadata.configs.push({ role, path: this.local(selected.path), fields: edited.fields });
  }
  async retire(name: string, owned: (text: string) => boolean): Promise<void> {
    const path = resolve(this.target.scope.cwd, name),
      before = await readProjectionFile(this.target.root, path);
    if (before.text !== null && owned(before.text)) {
      this.retired.push({ path, before });
    }
  }
  result(configs: ProjectionPlan["configs"]): ProjectionPlan {
    return {
      target: this.target,
      files: this.files,
      configs,
      current: this.files.every((file) => !file.changed) && this.retired.length === 0,
      retired: this.retired,
      native_configs: this.metadata,
      inputs: this.inputs,
    };
  }
}
function controlledFields(before: Record<string, unknown>, keys: string[]): string[][] {
  const fields = Object.fromEntries(keys.filter((key) => before[key] !== undefined).map((key) => [key, before[key]]));
  return reconcileFields({}, fields).fields;
}
function standaloneRuffFields(builder: ProjectionBuilder, selected: NativeSelection, text: string): string[][] {
  const native = configObject(text, selected.path);
  const known = new Set([...Object.keys(builder.policy.python.ruff), "src", "target-version"]);
  const previous = builder.previous(selected.path, "ruff");
  const unknown = Object.keys(native).find((key) => !known.has(key) && !previous.some((field) => field[0] === key));
  if (unknown) {
    throw new LintError(
      "config-conflict",
      `Project-local Ruff option ${unknown} in ${selected.path} is absent from shared policy`,
    );
  }
  return controlledFields(native, Object.keys(builder.policy.python.ruff));
}
async function pythonProjection(builder: ProjectionBuilder): Promise<ProjectionPlan["configs"]> {
  const { target, policy } = builder;
  const selected = await selectNative(
    target.root,
    target.scope.cwd,
    [".ruff.toml", "ruff.toml"],
    "pyproject.toml",
    false,
  );
  const text = selected.before.text;
  if (text === null) {
    throw new LintError("project-not-found", "Python manifest disappeared before projection");
  }
  if (!selected.path.endsWith("pyproject.toml")) {
    await builder.add(selected, "ruff", policy.python.ruff, standaloneRuffFields(builder, selected, text));
  } else {
    const previous = builder.previous(selected.path, "ruff");
    const owned = new Set(
      previous
        .filter((field) => field[0] === "tool" && field[1] === "ruff")
        .map((field) => field[2])
        .filter((key): key is string => key !== undefined),
    );
    const content = projectPython(text, policy.python, owned);
    await builder.record(
      selected,
      "ruff",
      editNativeConfig(content, selected.path, policy.python.ruff, previous, ["tool", "ruff"]),
    );
  }
  return { lint: selected.path, format: selected.path };
}
function preservedOverrides(before: Record<string, unknown>): Record<string, unknown>[] {
  if (!Array.isArray(before.overrides)) {
    return [];
  }
  return before.overrides
    .map((item: unknown) => {
      const { linter: _linter, assist: _assist, ...context } = object(item);
      return context;
    })
    .filter((context) => Object.keys(context).some((key) => key !== "includes"));
}
function ownedPrettier(text: string): boolean {
  try {
    return JSON.parse(text).$schema === PRETTIER_SCHEMA;
  } catch {
    return false;
  }
}
async function javascriptProjection(
  builder: ProjectionBuilder,
  versions: Partial<ToolVersions>,
): Promise<ProjectionPlan["configs"]> {
  const { target, policy } = builder;
  const scope = await collectLintScope(target, policy.javascript.exclude),
    leaves = await biomeLeaves(target, scope);
  const root = leaves[0];
  if (!root) {
    throw new LintError("projection-conflict", "Missing native Biome root");
  }
  for (const selected of leaves) {
    const desired = configObject(
      projectJavascript(
        target,
        policy.javascript,
        nestedBiomeScope(scope, target.scope.cwd, selected.path),
        versions[BIOME_PACKAGE] ?? "",
      ),
      "biome.json",
    );
    if (selected !== root) {
      desired.root = false;
    }
    const inherited = await biomeInputs(target, selected, root.path);
    validateBiomeInheritance(
      inherited.filter((input) => !leaves.some((leaf) => leaf.path === input.path)),
      desired,
    );
    builder.inputs.push(...inherited);
    const before = selected.before.text === null ? {} : configObject(selected.before.text, selected.path);
    desired.overrides = [...preservedOverrides(before), ...(desired.overrides as unknown[])];
    const oldPolicy = { linter: { rules: object(object(before.linter).rules) } };
    await builder.add(selected, "biome", desired, reconcileFields({}, oldPolicy).fields);
  }
  const format = await builder.add(
    await selectPrettier(target.root, target.scope.cwd),
    "prettier",
    policy.javascript.prettier,
  );
  await builder.retire("biome.justomp.jsonc", (text) => hasProjectionMarker(text, JS_MARKER));
  await builder.retire("eslint.justomp.config.mjs", (text) => hasProjectionMarker(text, JS_MARKER));
  await builder.retire("prettier.justomp.json", ownedPrettier);
  return { lint: root.path, format };
}
async function goProjection(builder: ProjectionBuilder): Promise<ProjectionPlan["configs"]> {
  const { target, policy } = builder;
  const selected = await selectNative(target.root, target.scope.cwd, GO_CONFIGS, ".golangci.yml");
  const before = selected.before.text === null ? {} : configObject(selected.before.text, selected.path);
  const fields = controlledFields(before, ["linters", "formatters", "severity", "issues", "output"]);
  const path = await builder.add(selected, "golangci", configObject(projectGo(policy.go), ".golangci.yml"), fields);
  await builder.retire("golangci.justomp.yml", (text) => hasProjectionMarker(text, GO_MARKER));
  return { lint: path, format: path };
}
/** Read-only freshness planning. Apply only after resolving again under the lease. */
export async function planProjection(
  target: LintTarget,
  policy: LintPolicy,
  versions: ToolVersions = {},
): Promise<ProjectionPlan> {
  const store = await LintStateStore.load(target.root);
  const builder = new ProjectionBuilder(
    target,
    policy,
    store.state.projects[target.project.project_id]?.native_configs,
  );
  switch (target.project.ecosystem) {
    case "python":
      return builder.result(await pythonProjection(builder));
    case "javascript":
      return builder.result(await javascriptProjection(builder, versions));
    case "go":
      return builder.result(await goProjection(builder));
  }
}
/** Changes are appended as published, including when a later file fails. */
export async function applyProjection(
  plan: ProjectionPlan,
  changes: PreparationChange[] = [],
): Promise<PreparationChange[]> {
  for (const file of plan.files) {
    if (!file.changed) {
      continue;
    }
    await publishProjectionFile(plan.target.root, file.path, file.before, file.content);
    changes.push({
      project_id: plan.target.project.project_id,
      path: relative(plan.target.root, file.path).replaceAll("\\", "/"),
      kind: file.before.text === null ? "created" : "updated",
    });
  }
  return changes;
}
/** Retire legacy snapshots only after the caller persists native ownership. */
export async function retireProjection(
  plan: ProjectionPlan,
  changes: PreparationChange[] = [],
): Promise<PreparationChange[]> {
  for (const file of plan.retired ?? []) {
    await removeProjectionFile(plan.target.root, file.path, file.before);
    changes.push({
      project_id: plan.target.project.project_id,
      path: relative(plan.target.root, file.path).replaceAll("\\", "/"),
      kind: "removed",
    });
  }
  return changes;
}
