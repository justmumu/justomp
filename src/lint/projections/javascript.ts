import { type BiomeRuleMap, type JavascriptPolicy } from "../../config/lint/model";
import { type LintScope } from "../scope";
import { type LintTarget } from "../targets";
import { stableVersion } from "../versions";

export const JS_MARKER = "// Generated by justomp; managed lint policy v1.\n";
export const PRETTIER_SCHEMA = "https://json.schemastore.org/prettierrc#justomp-owned-v1";

export function javascriptFrameworks(target: LintTarget) {
  const frameworks = target.project.frameworks.map((name) => name.toLowerCase());
  const next = frameworks.some((name) => ["next", "nextjs", "next.js"].includes(name));
  const react = next || frameworks.includes("react");
  return { react, next };
}

export function projectJavascript(
  target: LintTarget,
  policy: JavascriptPolicy,
  scope: LintScope,
  version: string,
): string {
  const biome = policy.biome;
  const { react, next } = javascriptFrameworks(target);
  const overrides: { includes: string[]; linter: { rules: BiomeRuleMap } }[] = [];
  const add = (includes: string[], rules: BiomeRuleMap) => overrides.push({ includes, linter: { rules } });
  if (scope.hasTypescript) {
    add(["**/*.{ts,cts,mts,tsx}"], biome.typed_rules);
  }
  if (react) {
    add(["**/*.{js,cjs,mjs,jsx,ts,cts,mts,tsx}"], biome.react_rules);
  }
  if (next) {
    add(["**/*.{js,jsx,ts,tsx}"], biome.next_rules);
  }
  add(["**/*.{test,spec}.{js,jsx,ts,tsx}", "**/__tests__/**"], biome.test_rules);
  return (
    JS_MARKER +
    JSON.stringify(
      {
        $schema: `https://biomejs.dev/schemas/${stableVersion(version)}/schema.json`,
        root: true,
        // Explicit --config-path still discovers nested configs unless the scanner ignores them.
        files: {
          includes: ["**", "!!**/biome.json", "!!**/biome.jsonc", ...scope.ignores.map((path) => `!!${path}`)],
        },
        vcs: { enabled: false },
        formatter: { enabled: false },
        linter: {
          enabled: true,
          domains: {
            react: "none",
            next: "none",
            test: "none",
            project: "none",
            types: "none",
          },
          rules: { preset: "none", ...biome.rules },
        },
        assist: {
          enabled: true,
          actions: {
            preset: "none",
            source: { organizeImports: biome.organize_imports },
          },
        },
        javascript: { globals: biome.globals },
        overrides,
      },
      null,
      2,
    ) +
    "\n"
  );
}
