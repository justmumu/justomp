import type { JavascriptPolicy, RuleMap } from "../../config/lint/model";
import type { LintScope } from "../scope";
import type { LintTarget } from "../targets";

export const JS_MARKER = "// Generated by justomp; managed lint policy v1.\n";
export const PRETTIER_SCHEMA =
  "https://json.schemastore.org/prettierrc#justomp-owned-v1";
const PLUGINS = [
  ["@typescript-eslint", "typescript-eslint", "tseslint", "tseslint.plugin"],
  [
    "simple-import-sort",
    "eslint-plugin-simple-import-sort",
    "importSort",
    "importSort",
  ],
  ["react-hooks", "eslint-plugin-react-hooks", "reactHooks", "reactHooks"],
  ["jsx-a11y", "eslint-plugin-jsx-a11y", "jsxA11y", "jsxA11y"],
  ["@next/next", "@next/eslint-plugin-next", "next", "next"],
] as const;
function javascriptFrameworks(target: LintTarget) {
  const react = target.project.frameworks.some((name) =>
    ["react", "next", "nextjs", "next.js"].includes(name.toLowerCase()),
  );
  const next = target.project.frameworks.some((name) =>
    ["next", "nextjs", "next.js"].includes(name.toLowerCase()),
  );
  return { react, next };
}
export function javascriptPlugins(
  policy: JavascriptPolicy,
  target: LintTarget,
  scope: LintScope,
): string[] {
  const { react, next } = javascriptFrameworks(target);
  const maps: RuleMap[] = [policy.eslint.rules, policy.eslint.test_rules];
  if (scope.hasTypescript) maps.push(policy.eslint.typed_rules);
  if (react) maps.push(policy.eslint.react_rules);
  if (next) maps.push(policy.eslint.next_rules);
  return PLUGINS.filter(
    ([prefix]) =>
      (prefix === "@typescript-eslint" && scope.hasTypescript) ||
      maps.some((map) =>
        Object.keys(map).some((key) => key.startsWith(`${prefix}/`)),
      ),
  ).map(([, pkg]) => pkg);
}
export function projectJavascript(
  target: LintTarget,
  policy: JavascriptPolicy,
  scope: LintScope,
): string {
  const packages = javascriptPlugins(policy, target, scope);
  const selected = PLUGINS.filter(([, pkg]) => packages.includes(pkg));
  const data = {
    policy: policy.eslint,
    ignores: scope.ignores,
    typed: scope.hasTypescript,
    ...javascriptFrameworks(target),
  };
  // Only fixed identifiers/imports become code. All project/policy strings are JSON data.
  const imports = selected
    .map(
      ([, pkg, identifier]) =>
        `const ${identifier} = require(${JSON.stringify(pkg)});\n`,
    )
    .join("");
  const plugins = selected
    .map(([name, , , expression]) => `${JSON.stringify(name)}: ${expression}`)
    .join(", ");
  return `${JS_MARKER}import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
${imports}const cwd = fileURLToPath(new URL(".", import.meta.url));
const data = JSON.parse(${JSON.stringify(JSON.stringify(data))});
const config = [
  { ignores: data.ignores },
  {
    files: ["**/*.{js,cjs,mjs,jsx,ts,cts,mts,tsx}"],
    plugins: { ${plugins} },
    languageOptions: { ecmaVersion: "latest", globals: data.policy.globals, parserOptions: { ecmaFeatures: { jsx: true } } },
    rules: data.policy.rules,
  },
];
${
  scope.hasTypescript
    ? `config.push({
  files: ["**/*.{ts,cts,mts,tsx}"],
  languageOptions: { parser: tseslint.parser, parserOptions: { projectService: true, tsconfigRootDir: cwd } },
  rules: data.policy.typed_rules,
});`
    : ""
}
if (data.react) config.push({ files: ["**/*.{js,cjs,mjs,jsx,ts,cts,mts,tsx}"], rules: data.policy.react_rules });
if (data.next) config.push({ files: ["**/*.{js,jsx,ts,tsx}"], settings: { next: { rootDir: cwd } }, rules: data.policy.next_rules });
config.push({ files: ["**/*.{test,spec}.{js,jsx,ts,tsx}", "**/__tests__/**"], rules: data.policy.test_rules });
export default config;
`;
}
