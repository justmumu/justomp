import { expect, test } from "bun:test";
import { resolveLintConfig } from "../../../src/config/lint/resolve";
import { assertGoFormatPolicy, isGeneratedGo } from "../../../src/format/go-policy";

test("Go selection policy rejects native-only filters instead of reporting skipped source as unchanged", () => {
  const policy = resolveLintConfig().policy.go;
  expect(() => assertGoFormatPolicy(policy)).not.toThrow();
  policy.golangci.formatters.exclusions.paths = [];
  policy.golangci.formatters.exclusions.generated = "disable";
  expect(() => assertGoFormatPolicy(policy)).not.toThrow();
  policy.golangci.formatters.exclusions.paths = ["^private/"];
  expect(() => assertGoFormatPolicy(policy)).toThrow("formatters.exclusions.paths");
  policy.golangci.formatters.exclusions.paths = [];
  policy.golangci.formatters.exclusions.generated = "lax";
  expect(() => assertGoFormatPolicy(policy)).toThrow("strict or disable");
});

test("generated Go filtering keeps CRLF and indented markers outside the write scope", () => {
  expect(isGeneratedGo("\uFEFF\t// Code generated by fixture. DO NOT EDIT.\r\npackage test\r\n")).toBe(true);
  expect(isGeneratedGo("package test\n")).toBe(false);
});
