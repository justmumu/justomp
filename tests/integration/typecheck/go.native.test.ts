test("go.work imports selected dependencies but excludes independent child tests and node_modules", async () => {
  const f = await fixture(true);
  await writeFile(
    join(f.root, "main.go"),
    'package main\nimport "example.test/child"\nfunc main() { println(child.Value) }\n',
  );
  await writeFile(
    join(f.root, "child/broken_test.go"),
    'package child\nvar Broken int = "wrong"\n',
  );
  await mkdir(join(f.root, "node_modules/foreign"), { recursive: true });
  await writeFile(join(f.root, "node_modules/foreign/bad.go"), "not Go source");
  await writeFile(join(f.root, "go.work.sum"), "");
  await writeFile(join(f.root, "go.sum"), "");
  const before = await f.bytes(),
    tempBefore = await scratch();
  const [root] = await goAdapter.check(await f.checkContext());
  expect(root?.status, JSON.stringify(root)).toBe("passed");
  const [child] = await goAdapter.check(await f.checkContext(1));
  expect(child?.status, JSON.stringify(child)).toBe("failed");
  expect(
    child?.diagnostics.some(
      (d) =>
        d.project_id === "go:child/go.mod" && d.path === "child/broken_test.go",
    ),
  ).toBe(true);
  expect(await f.bytes()).toEqual(before);
  expect(await scratch()).toEqual(tempBefore);
}, 90000);

test("shared tags and current platform determine active Go source; empty is not success", async () => {
  const f = await fixture();
  await writeFile(
    join(f.root, "tagged.go"),
    '//go:build selected\n\npackage main\nvar Value int = "wrong"\n',
  );
  await writeFile(
    join(f.root, "inactive_plan9.go"),
    'package main\nvar Inactive int = "wrong"\n',
  );
  const [clean] = await goAdapter.check(await f.checkContext());
  expect(clean?.status, JSON.stringify(clean)).toBe("passed");
  expect(clean?.context?.goos).toBe(
    process.platform === "darwin" ? "darwin" : "linux",
  );
  expect(clean?.context?.goarch).toBe(
    process.arch === "arm64" ? "arm64" : "amd64",
  );
  expect(clean?.context?.build_tags).toEqual([]);
  f.context.policy.go.build_tags = ["selected"];
  const [tagged] = await goAdapter.check(await f.checkContext());
  expect(tagged?.status).toBe("failed");
  expect(tagged?.context?.build_tags).toEqual(["selected"]);
  f.context.policy.go.build_tags = [];
  await rm(join(f.root, "main.go"));
  expect((await goAdapter.check(await f.checkContext()))[0]?.status).toBe(
    "no-sources",
  );
  await rm(join(f.root, "tagged.go"));
  await rm(join(f.root, "inactive_plan9.go"));
  expect((await goAdapter.check(await f.checkContext()))[0]?.status).toBe(
    "no-sources",
  );
}, 90000);

test("absent Go, incompatible runtime, missing module cache and absent CGo compiler stay incomplete", async () => {
  const f = await fixture();
  const ctx = await f.checkContext(),
    env = ctx.target.scope.env;
  const path = env.PATH;
  env.PATH = "";
  expect((await goAdapter.check(ctx))[0]?.status).toBe("not-run");
  await expect(goAdapter.preflight(f.context)).rejects.toThrow("not installed");
  env.PATH = path;
  await writeFile(join(f.root, "go.mod"), "module example.test/app\ngo 1.99\n");
  const [runtime] = await goAdapter.check(ctx);
  expect(runtime?.status).toBe("not-run");
  expect(runtime?.reason).toContain("requires Go");
  await writeFile(
    join(f.root, "go.mod"),
    "module example.test/app\ngo 1.25\nrequire example.test/not-cached v1.0.0\n",
  );
  await writeFile(
    join(f.root, "main.go"),
    'package main\nimport _ "example.test/not-cached"\nfunc main() {}\n',
  );
  env.GOMODCACHE = join(f.root, ".cache/modules");
  const before = await f.bytes();
  const [missing] = await goAdapter.check(ctx);
  expect(missing?.status, JSON.stringify(missing)).toBe("not-run");
  expect(missing?.reason).toContain("dependency_sync");
  expect(await f.bytes()).toEqual(before);
  await writeFile(join(f.root, "go.mod"), "module example.test/app\ngo 1.25\n");
  await writeFile(
    join(f.root, "main.go"),
    'package main\n/* int value = 1; */\nimport "C"\nfunc main() { println(C.value) }\n',
  );
  env.CGO_ENABLED = "1";
  env.CC = "justomp-absent-cc";
  const [cgo] = await goAdapter.check(ctx);
  expect(cgo?.status, JSON.stringify(cgo)).toBe("not-run");
  expect(cgo?.reason).toContain("compiler");
}, 90000);

test("cancellation waits for native compiler shutdown before deleting binary and workspace scratch", async () => {
  const f = await fixture(true);
  const ctx = await f.checkContext(),
    controller = new AbortController();
  ctx.target.scope.env.GOCACHE = join(f.root, ".cache/cancel-build");
  ctx.target.scope.env.CGO_ENABLED = "0";
  const before = await f.bytes(),
    tempBefore = await scratch();
  const original = runtime.lintManagerContext;
  let timer: ReturnType<typeof setTimeout> | undefined;
  const hook = spyOn(runtime, "lintManagerContext").mockImplementation(
    async (...args) => {
      const native = await original(...args);
      return {
        ...native,
        run(step) {
          const running = native.run(step);
          if (step.args[0] === "test")
            timer = setTimeout(() => controller.abort(), 50);
          return running;
        },
      };
    },
  );
  try {
    const [check] = await goAdapter.check({
      ...ctx,
      signal: controller.signal,
    });
    expect(check?.status, JSON.stringify(check)).toBe("not-run");
    expect(check?.cancelled).toBe(true);
    expect(await f.bytes()).toEqual(before);
    expect(await scratch()).toEqual(tempBefore);
  } finally {
    if (timer) clearTimeout(timer);
    hook.mockRestore();
  }
}, 90000);

test("workspace checksum completion during native compilation preserves all original metadata", async () => {
  const f = await fixture(true);
  const proxy = join(f.root, ".cache/proxy"),
    seed = join(f.root, ".cache/seed");
  await createGoProxy(proxy);
  await mkdir(seed, { recursive: true });
  await writeFile(
    join(seed, "go.mod"),
    "module example.test/seed\ngo 1.25\nrequire example.test/lib v1.0.0\n",
  );
  const ctx = await f.checkContext();
  ctx.target.scope.env.GOMODCACHE = join(f.root, ".cache/modules");
  const downloaded = await runProcess(
    Bun.which("go") ?? "go",
    ["mod", "download", "all"],
    {
      cwd: seed,
      env: {
        ...ctx.target.scope.env,
        GOWORK: "off",
        GOPROXY: `file://${proxy}`,
        GOSUMDB: "off",
        GOTOOLCHAIN: "local",
        GOFLAGS: "",
      },
    },
  );
  expect(downloaded.exit_code, downloaded.stderr).toBe(0);
  await writeFile(
    join(f.root, "go.mod"),
    "module example.test/app\ngo 1.25\nrequire example.test/lib v1.0.0\n",
  );
  await writeFile(
    join(f.root, "main.go"),
    'package main\nimport _ "example.test/lib"\nfunc main() {}\n',
  );
  const before = await f.bytes(),
    tempBefore = await scratch();
  const [check] = await goAdapter.check(ctx);
  expect(check?.status, JSON.stringify(check)).toBe("passed");
  expect(await f.bytes()).toEqual(before);
  expect(await scratch()).toEqual(tempBefore);
}, 90000);
