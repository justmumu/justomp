const cleanups: (() => Promise<void>)[] = [];
afterEach(async () => {
  for (const cleanup of cleanups.splice(0).reverse()) await cleanup();
});
const scratch = async () =>
  (await readdir(tmpdir()))
    .filter(
      (name) =>
        name.startsWith("justomp-go-typecheck-") ||
        name.startsWith("justomp-go-work-"),
    )
    .sort();
async function fixture(workspace = false) {
  const f = await goFixture(workspace);
  cleanups.push(f.dispose);
  return f;
}

test("native Go compiles source, internal tests and external tests, including generated source", async () => {
  const f = await fixture();
  for (const [path, source] of [
    [
      "main.go",
      'package main\nfunc main() { var value int = "wrong"; _ = value }\n',
    ],
    [
      "main_test.go",
      'package main\nimport "testing"\nfunc TestValue(t *testing.T) { var value int = "wrong"; _ = value }\n',
    ],
    [
      "external_test.go",
      'package main_test\nimport "testing"\nfunc TestExternal(t *testing.T) { var value int = "wrong"; _ = value }\n',
    ],
    [
      "generated.go",
      '// Code generated by fixture. DO NOT EDIT.\npackage main\nvar Value int = "wrong"\n',
    ],
  ] as const) {
    await writeFile(join(f.root, "main.go"), "package main\nfunc main() {}\n");
    await writeFile(join(f.root, path), source);
    const [check] = await goAdapter.check(await f.checkContext());
    expect(check?.status, JSON.stringify(check)).toBe("failed");
    expect(
      check?.diagnostics.some(
        (d) =>
          d.project_path === path &&
          d.project_id === "go:go.mod" &&
          d.line &&
          d.message.includes("cannot use"),
      ),
    ).toBe(true);
    await rm(join(f.root, path));
  }
}, 90000);

test("compiler-only Go never runs init, TestMain or test bodies; vet stays outside typecheck", async () => {
  const f = await fixture();
  const sentinel = join(f.root, "EXECUTED");
  const write = `os.WriteFile(${JSON.stringify(sentinel)}, []byte("executed"), 0600)`;
  await writeFile(
    join(f.root, "main.go"),
    `package main\nimport ("os"; "fmt")\nfunc init() { ${write} }\nfunc main() {}\nfunc Value() { fmt.Printf("%d", "vet only") }\n`,
  );
  await writeFile(
    join(f.root, "main_test.go"),
    `package main\nimport ("os"; "testing")\nfunc init() { ${write} }\nfunc TestMain(m *testing.M) { ${write}; os.Exit(m.Run()) }\nfunc TestValue(t *testing.T) { ${write} }\n`,
  );
  const before = await f.bytes(),
    tempBefore = await scratch();
  await f.prepare();
  const ctx = await f.checkContext();
  expect(await goAdapter.verifyTools(ctx)).toBe(true);
  expect(await projectionCurrent(goAdapter, ctx)).toBe(true);
  expect(ctx.projection.files).toEqual([]);
  const [check] = await goAdapter.check(ctx);
  expect(check?.status, JSON.stringify(check)).toBe("passed");
  await expect(access(sentinel)).rejects.toThrow();
  expect(await f.bytes()).toEqual(before);
  expect(await scratch()).toEqual(tempBefore);
  expect(f.context.changes).toEqual([]);
}, 90000);

